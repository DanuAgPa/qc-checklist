/** Memformat Date menjadi string YYYY-MM-DD menggunakan zona waktu lokal server. */
export function formatDateISO(date: Date): string {
  const year = date.getFullYear();
  const month = String(date.getMonth() + 1).padStart(2, '0');
  const day = String(date.getDate()).padStart(2, '0');
  return `${year}-${month}-${day}`;
}

/** Memvalidasi string "YYYY-MM-DD" dan mengembalikan Date pukul 00:00 waktu lokal. */
export function parseDateISO(value: string): Date | null {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(value)) return null;
  const date = new Date(`${value}T00:00:00`);
  return Number.isNaN(date.getTime()) ? null : date;
}
